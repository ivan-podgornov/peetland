/**
 * Баланс бомжа: значения, которые подбираются, чтобы жизнь бомжа шла как задумано. Свойства
 * модели, которые не настраиваются, лежат статическими полями своих классов
 */

/** Сколько платят за одну пустую бутылку, в долларах */
export const BOTTLE_PRICE = 10;

/** Со сколькими бутылками бомж идёт их сдавать: столько с собой таскать уже тяжело */
export const BOTTLES_TO_SELL = 10;

/**
 * Сколько долларов бомжу хватает: с таким богатством — деньгами вместе с выручкой за бутылки — он не
 * попрошайничает и не роется в мусорках
 */
export const ENOUGH_MONEY = 200;

/** Шанс найти бутылку за одну попытку, раз в секунду (см. TryLuckTask) */
export const BOTTLE_FIND_CHANCE = 1 / 60;

/** Сколько бутылок NPC ищет в мусорке за один заход */
export const MAX_BOTTLES_PER_VISIT = 5;

/** Сколько бутылок NPC может унести */
export const MAX_BOTTLES = 15;

/** Шанс получить подачку за одну попытку, раз в секунду (см. TryLuckTask) */
export const BEGGING_CHANCE = 1 / 40;

/** Сколько долларов NPC получает в одной подачке */
export const BEGGING_REWARD = 10;

/** Сколько подачек NPC получает за один заход, если стыд не остановит его раньше */
export const MAX_BEGGING_REWARDS_PER_VISIT = 10;

/**
 * Стыд, при котором NPC перестаёт попрошайничать. Подобран вместе с приростом стыда за попытку (см.
 * BEGGING_SHAME в @peetland/psyche): при средней совестливости и нулевом стартовом стыде порог
 * достигается примерно за 600 попыток, а на одну подачку в среднем уходит 40 попыток
 */
export const BEGGING_SHAME_LIMIT = 60;
