/** Категория потребности. От неё зависит, какой слой корневой задачи NPC её удовлетворяет */
export enum NeedCategory {
  /** Жизненная потребность: то, без чего NPC не может жить, например сытость */
  Vital = 'vital',
  /** Зависимость: то, без чего NPC жить не хочет, например выпить пива */
  Addiction = 'addiction',
}
