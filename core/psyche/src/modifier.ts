/**
 * Модификаторы — множители, которыми черты характера меняют то, как задачи работают с персонажем.
 * Например, удачливость меняет шанс, с которым персонажу везёт
 */
export enum Modifier {
  /**
   * Множитель шанса, с которым персонажу везёт в игре. Умножает не сам шанс, а соотношение удач и
   * неудач: шанс / (1 − шанс), чтобы шанс не выходил за 1
   */
  Chance = 'chance',
}
