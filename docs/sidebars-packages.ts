import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';

/** Пакеты одного слоя: категория со страницей-списком и README пакетов из папки слоя */
function layer(name: string) {
  return {
    type: 'category' as const,
    label: name,
    link: {
      type: 'generated-index' as const,
      slug: `/${name}`,
    },
    items: [
      {
        type: 'autogenerated' as const,
        dirName: name,
      },
    ],
  };
}

const sidebars: SidebarsConfig = {
  packages: [
    {
      type: 'category',
      label: 'Пакеты',
      link: {
        type: 'generated-index',
        slug: '/',
        description: 'README пакетов монорепозитория, сгруппированные по слоям',
      },
      collapsible: false,
      items: [layer('toolkit'), layer('core'), layer('mod')],
    },
  ],
};

export default sidebars;
