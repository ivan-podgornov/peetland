/** Результат выполнения задачи */
export type TaskResult = 'success' | 'running' | 'failed';

/**
 * Примитивная задача.
 *
 * `TState` — состояние мира, по которому задача проверяет, можно ли её выполнить, и считает
 * эффекты. В нём лежат данные и сущности, доступные только на чтение, и задачи их не меняют.
 * `TContext` — контекст исполнения: мутабельные сущности, которым задача отдаёт команды, например
 * актор. Контекст получают только методы, которые что-то меняют: `start`, `update` и `stop`.
 * `canExecute` и `applyEffects` только читают состояние и считают эффекты, поэтому контекст им не
 * нужен.
 *
 * Экземпляр задачи одновременно исполняет только один агент, поэтому состояние исполнения задача
 * хранит в своих полях и сбрасывает его в `start`
 */
export interface PrimitiveTask<TState, TContext> {
  /** Название задачи. Используется для отладки и логгирования */
  name: string;

  /** Проверяет можно ли выполнить задачу при указанном состоянии мира */
  canExecute(state: TState): boolean;

  /**
   * Применяет эффекты к состоянию мира. Функция иммутабельная, поэтому она не мутирует состояние,
   * а возвращает новое с применёнными эффектами. Если эффекту нужно поменять сущность из
   * состояния, задача пишет в её копию и кладёт копию в новое состояние
   */
  applyEffects(state: TState): TState;

  /** Начинает выполнение задачи */
  start(state: TState, context: TContext): TaskResult;

  /** Вызывается каждый тик с обновлённым состоянием мира */
  update(state: TState, context: TContext): TaskResult;

  /** Прекращает выполение задачи. Вызывается, когда нужно завершить задачу извне */
  stop(context: TContext): void;
}

export interface CompoundTask<TState, TContext> {
  /** Название задачи. Используется для отладки и логгирования */
  name: string;

  /**
   * Задача — транзакция: её примитивные задачи в плане нельзя прервать посередине, например
   * покупку. Если агента мягко останавливают (см. IHTN.softStop), он сначала доделывает
   * транзакцию. Транзакция внутри транзакции — часть внешней. По умолчанию задача не транзакция
   */
  transaction?: boolean;

  /** Методы выполнения составной задачи */
  methods: Method<TState, TContext>[];
}

export type Task<TState, TContext> =
  PrimitiveTask<TState, TContext> | CompoundTask<TState, TContext>;

/**
 * Подзадачи метода: готовый список или функция, которая собирает список по состоянию мира. Функцию
 * планировщик вызывает, только если предусловия метода подошли, и передаёт ей то же состояние, на
 * котором проверялись предусловия
 */
export type MethodTasks<TState, TContext> =
  Task<TState, TContext>[] | ((state: TState) => Task<TState, TContext>[]);

export interface Method<TState, TContext> {
  /** Название метода выполнения составной задачи */
  name: string;

  /**
   * Задачи, которые нужно выполнить, чтобы реализовать метод. Если задачи зависят от состояния мира,
   * например, нужно идти к ближайшему магазину, вместо списка передаётся функция, которая собирает
   * задачи по состоянию (см. MethodTasks)
   */
  tasks: MethodTasks<TState, TContext>;

  /**
   * Проверяет, подходит ли метод для планирования, при текущем состоянии мира
   * @param state - текущее состояние мира
   */
  preconditions(state: TState): boolean;
}

/** Проверяет, является ли задача примитивной */
export function isPrimitive<TState, TContext>(
  task: Task<TState, TContext>
): task is PrimitiveTask<TState, TContext> {
  return 'canExecute' in task;
}
