/** Пишет сообщения в лог. Куда именно, решает реализация */
export interface ILogger {
  /** Пишет сообщение о том, что происходит в штатном режиме */
  info(message: string): void;

  /** Пишет сообщение о том, что что-то пошло не так, но работа продолжается */
  warn(message: string): void;

  /** Пишет сообщение об ошибке */
  error(message: string): void;
}
