import type { Observable } from '@peetland/events';

export interface ITimer {
  /**
   * Возвращает новый Observable, который раз в period миллисекунд сообщает, сколько миллисекунд
   * прошло с прошлого значения, а для первого значения — с подписки. Каждый вызов создаёт
   * отдельный Observable со своим отсчётом времени, поэтому его не нужно делить с другими
   * @param period - как часто сообщать о прошедшем времени, в миллисекундах
   */
  interval(period: number): Observable<number>;
}

/** Слепок момента времени: день и время суток */
export type TimeState = Readonly<{
  /** Номер дня по счёту, с 1. Растёт на 1 каждую полночь */
  day: number;
  /** Час, от 0 до 23 */
  hours: number;
  /** Минуты текущего часа, от 0 до 59 */
  minutes: number;
}>;

/**
 * Время только на чтение: день и время суток. Так время лежит в состоянии NPC: планирование читает
 * его, а эффекты задач пишут в копию из clone()
 */
export interface IReadonlyTime {
  /** Номер дня по счёту, с 1. Растёт на 1 каждую полночь */
  readonly day: number;
  /** Час, от 0 до 23 */
  readonly hours: number;
  /** Минуты текущего часа, от 0 до 59 */
  readonly minutes: number;

  /**
   * Возвращает слепок времени на момент вызова. Время идёт, и геттеры между вызовами
   * возвращают разное, а слепок не меняется
   */
  getState(): TimeState;

  /**
   * Возвращает копию времени на момент вызова, которую можно менять. Копия стоит на месте, пока её
   * не выставят, а исходное время копия не меняет
   */
  clone(): ITime;
}

/** Время, которое можно выставить. Стоит на месте, пока его не выставят (см. ManualTime) */
export interface ITime extends IReadonlyTime {
  /**
   * Выставляет время.
   * Выбрасывает RangeError, если day не целое от 1, hours не целое от 0 до 23 или minutes не целое
   * от 0 до 59
   * @param state - слепок времени, которое нужно выставить
   */
  set(state: TimeState): void;
}
